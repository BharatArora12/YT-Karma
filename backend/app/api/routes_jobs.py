import json
import threading
import uuid
from datetime import datetime, timezone
from typing import List
from fastapi import APIRouter, HTTPException, BackgroundTasks
from app.config import settings
from app.models.schemas import (
    JobCreateRequest,
    JobResponse,
    JobStatus,
    TranscriptData,
)
from app.services.pipeline_worker import (
    ShortsPipelineWorker,
    save_job,
    get_job,
    list_jobs,
)

router = APIRouter(prefix="/api/jobs", tags=["Jobs Pipeline"])


@router.post("", response_model=JobResponse, status_code=202)
def create_job(req: JobCreateRequest):
    """
    Triggers the 5-step automated Shorts pipeline asynchronously.
    """
    if not req.youtube_url or "youtube.com" not in req.youtube_url and "youtu.be" not in req.youtube_url:
        raise HTTPException(status_code=400, detail="Invalid YouTube URL provided.")

    job_id = f"job_{uuid.uuid4().hex[:10]}"
    now = datetime.now(timezone.utc).isoformat()

    job = JobResponse(
        job_id=job_id,
        youtube_url=req.youtube_url.strip(),
        status=JobStatus.QUEUED,
        progress=0,
        current_step="Job queued for processing",
        clips=[],
        created_at=now,
        updated_at=now,
    )
    save_job(job)

    # Spawn asynchronous worker execution in a separate daemon thread
    worker_thread = threading.Thread(
        target=ShortsPipelineWorker.execute_pipeline,
        args=(job_id, req.youtube_url, req.clip_count, req.min_duration, req.max_duration),
        daemon=True,
    )
    worker_thread.start()

    return job


@router.get("", response_model=List[JobResponse])
def get_all_jobs():
    """Lists all recent pipeline jobs."""
    return list_jobs()


@router.get("/{job_id}", response_model=JobResponse)
def get_job_status(job_id: str):
    """Retrieves real-time status and generated clips for a specific job."""
    job = get_job(job_id)
    if not job:
        raise HTTPException(status_code=404, detail=f"Job '{job_id}' not found.")
    return job


@router.get("/{job_id}/transcript", response_model=TranscriptData)
def get_job_transcript(job_id: str):
    """Retrieves the word-level timestamped transcript generated by faster-whisper."""
    tpath = settings.transcripts_dir / f"{job_id}.json"
    if not tpath.exists():
        raise HTTPException(status_code=404, detail="Transcript not ready or not found.")
    try:
        with open(tpath, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to read transcript: {str(e)}")


@router.post("/{job_id}/retry", response_model=JobResponse, status_code=202)
def retry_job(job_id: str):
    """
    Retries or resumes a failed pipeline job.
    """
    job = get_job(job_id)
    if not job:
        raise HTTPException(status_code=404, detail=f"Job '{job_id}' not found.")

    now = datetime.now(timezone.utc).isoformat()
    job.status = JobStatus.QUEUED
    job.progress = 0
    job.current_step = "Retrying pipeline execution..."
    job.error_message = None
    job.updated_at = now
    save_job(job)

    worker_thread = threading.Thread(
        target=ShortsPipelineWorker.execute_pipeline,
        args=(job_id, job.youtube_url),
        daemon=True,
    )
    worker_thread.start()

    return job

